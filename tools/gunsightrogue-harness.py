# --- static checks: the toc, the generic module, the baked art ---------------------------------------------------------------

TEXTURES = ("rogue_dead", "rogue_ready", "rogue_flash", "rogue_finish", "rogue_gem", "rogue_atlas",
            "rogue_lit_1", "rogue_lit_2", "rogue_lit_3", "rogue_lit_4", "rogue_lit_5")


def static_checks() -> list[str]:
    errs: list[str] = []
    toc = [ln.strip() for ln in TOC.read_text(encoding="utf-8").splitlines()]
    order = ["Modules/CombatHud/GunsightAreas.lua", "Modules/CombatHud/RogueArt.lua", "Modules/CombatHud/RogueState.lua",
             "Modules/CombatHud/GunsightRogue.lua"]
    for name in order:
        if name not in toc:
            errs.append(f"{name} is not in the toc")
    if all(n in toc for n in order):
        idx = [toc.index(n) for n in order]
        if idx != sorted(idx):
            errs.append("toc order must be GunsightAreas, RogueArt, RogueState, GunsightRogue")
    classes = re.search(r"local CLASSES = (\{[^}]*\})", CLASS)
    if not classes or "ROGUE" in classes.group(1):
        errs.append("GunsightClass.lua must not list ROGUE in its classes")
    # Its combo path (and the ROGUE / DRUID branch that picks it) stays for the gunsightclass harness, which mounts the spec
    # directly; the CLASSES list above is what decides whether a live Rogue gets it.
    for t in TEXTURES:
        p = MEDIA / f"{t}.tga"
        if not p.exists():
            errs.append(f"missing texture {t}.tga")
    # the generated files are exactly what the generator writes
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, FS_ASSET_OUTPUT_DIR=tmp, FS_ROGUE_LUA=str(Path(tmp) / "RogueArt.lua"))
        env.pop("FS_ROGUE_PREVIEW", None)
        res = subprocess.run([sys.executable, str(GENERATOR)], env=env, capture_output=True, text=True)
        if res.returncode != 0:
            errs.append("the generator failed: " + res.stderr[-300:])
        else:
            for t in TEXTURES:
                a, b = MEDIA / f"{t}.tga", Path(tmp) / f"{t}.tga"
                if a.exists() and a.read_bytes() != b.read_bytes():
                    errs.append(f"{t}.tga is not what the generator writes (regenerate)")
            if (HUD / "RogueArt.lua").read_text(encoding="utf-8") != (Path(tmp) / "RogueArt.lua").read_text(encoding="utf-8"):
                errs.append("RogueArt.lua is not what the generator writes (regenerate)")
    # no secret reaches a comparison: the module never indexes or compares power values (spot check of the forbidden patterns)
    for pat in (r"UnitPower\([^)]*\)\s*[<>=]",):
        if re.search(pat, MODULE):
            errs.append(f"GunsightRogue.lua compares a power value ({pat})")
    for word in ("bot", "automation"):
        if re.search(r"(?<![A-Za-z])" + word + r"(?![A-Za-z])", MODULE + DATA):
            errs.append(f"the word {word!r} appears in the Rogue files")
    return errs


def main() -> int:
    failures = 0
    for err in static_checks():
        failures += 1
        print(f"FAIL  static: {err}")
    for name, body in CASES:
        err = run_case(body)
        if err is None:
            print(f"ok    {name}")
        else:
            failures += 1
            print(f"FAIL  {name}: {err}")
    err = run_real_case()
    name = "under_the_real_areas_the_host_follows_the_target_and_the_module_stops_with_it"
    if err is None:
        print(f"ok    {name}")
    else:
        failures += 1
        print(f"FAIL  {name}: {err}")
    total = len(CASES) + 1
    print(f"{total - min(failures, total)}/{total} checks passed")
    return int(failures > 0)


