// Bakes the talent spec background scenes (lib.js + scenes/*.js) into the addon's flipbook sheets and manifest.
//
//   node tools/assets/talentbg/bake.mjs sheets [mediaDir] [manifest.lua]   write every sheet and the manifest
//   node tools/assets/talentbg/bake.mjs check  [mediaDir] [manifest.lua]   exit 1 unless the committed files equal a fresh bake
//   node tools/assets/talentbg/bake.mjs preview <id|CLASS|all> out.png [scale] [frames]
//                                                                         a contact sheet: one row per scene, frames across
//   node tools/assets/talentbg/bake.mjs stats [id|CLASS|all]               colours and loop seam per scene
//
// A sheet is one 1024 x 1024 32-bit TGA per spec: 24 frames of 156 x 236 in 6 columns x 4 rows, each frame with a one texel
// replicated gutter (cell pitch 158 x 238) so a bilinear sample never bleeds a neighbour. Alpha is 255 everywhere: the runtime
// insets the picture inside the panel's cut corners, so nothing is baked for them.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const ADDON = path.join(ROOT, 'forever-stuwave');
const DEFAULT_MEDIA = path.join(ADDON, 'Media/Textures');
const DEFAULT_MANIFEST = path.join(ADDON, 'Modules/Skins/TalentBgArt.lua');

export const FRAMES = 24, FPS = 8, COLS = 6, ROWS = 4, CW = 158, CH = 238, SHEET = 1024;
const CLASS_ORDER = ['WARRIOR', 'PALADIN', 'HUNTER', 'ROGUE', 'PRIEST', 'SHAMAN', 'MAGE', 'WARLOCK', 'DRUID'];

export function loadScenes(only) {
  const ctx = vm.createContext({ Math, Map, Set, Uint8Array, Uint8ClampedArray, Int16Array, Float64Array, Float32Array, Uint16Array, Uint32Array, Int32Array, Array, Object, Number, Error, console });
  const files = [path.join(HERE, 'lib.js')];
  const dir = path.join(HERE, 'scenes');
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort()) {
    if (only && f.replace(/\.js$/, '') !== only) continue;
    files.push(path.join(dir, f));
  }
  for (const f of files) vm.runInContext(fs.readFileSync(f, 'utf8'), ctx, { filename: f });
  const TBG = vm.runInContext('TBG', ctx);
  const W = vm.runInContext('W', ctx), H = vm.runInContext('H', ctx);
  if (W !== 156 || H !== 236) throw new Error(`scene canvas is ${W} x ${H}, expected 156 x 236`);
  const seen = new Set();
  for (const s of TBG.scenes) {
    const key = s.cls + ':' + s.tree;
    if (seen.has(key) || seen.has(s.id)) throw new Error('duplicate scene ' + s.id);
    seen.add(key); seen.add(s.id);
    if (!/^[a-z]+_[a-z]+$/.test(s.id)) throw new Error('scene id must be class_spec in lower case: ' + s.id);
  }
  TBG.scenes.sort((a, b) => (CLASS_ORDER.indexOf(a.cls) - CLASS_ORDER.indexOf(b.cls)) || (a.tree - b.tree));
  return { TBG, W, H };
}

function pick(TBG, sel) {
  if (!sel || sel === 'all') return TBG.scenes;
  const out = TBG.scenes.filter(s => s.id === sel || s.cls === sel.toUpperCase());
  if (!out.length) throw new Error('no scene matches ' + sel);
  return out;
}

function frames(TBG, s) {
  const out = [];
  for (let f = 0; f < FRAMES; f++) out.push(Uint8Array.from(TBG.render(s, f, FRAMES)));
  return out;
}

function sheetTga(fr, W, H) {
  const head = Buffer.alloc(18);
  head.writeUInt8(0, 0); head.writeUInt8(0, 1); head.writeUInt8(2, 2);
  head.writeUInt16LE(SHEET, 12); head.writeUInt16LE(SHEET, 14); head.writeUInt8(32, 16); head.writeUInt8(0x28, 17);
  const body = Buffer.alloc(SHEET * SHEET * 4);
  for (let i = 3; i < body.length; i += 4) body[i] = 255;
  fr.forEach((d, f) => {
    const ox = (f % COLS) * CW, oy = Math.floor(f / COLS) * CH;
    for (let y = 0; y < CH; y++) {
      const sy = Math.min(H - 1, Math.max(0, y - 1));
      for (let x = 0; x < CW; x++) {
        const sx = Math.min(W - 1, Math.max(0, x - 1)), i = ((oy + y) * SHEET + ox + x) * 4, j = (sy * W + sx) * 4;
        body[i] = d[j + 2]; body[i + 1] = d[j + 1]; body[i + 2] = d[j]; body[i + 3] = 255;
      }
    }
  });
  return Buffer.concat([head, body]);
}

const sheetName = s => 'talentbg_' + s.id;

function manifest(scenes) {
  const by = {};
  for (const s of scenes) (by[s.cls] = by[s.cls] || [])[s.tree - 1] = s;
  const lines = [
    "-- Forever STUwave: the talent spec background flipbooks.",
    "-- GENERATED by tools/assets/talentbg/bake.mjs; do not edit (talentbg-harness.py checks it).",
    "-- One sheet per spec: FRAMES cells of W x H texels at pitch CW x CH (one texel gutter round each), COLS across, in a",
    "-- SHEET x SHEET texture. sheets[class token][tree index left to right] = file name in Media/Textures.",
    "",
    "local _, FS = ...",
    "",
    "FS.TalentBgArt = {",
    `    W = 156, H = 236, CW = ${CW}, CH = ${CH}, COLS = ${COLS}, ROWS = ${ROWS}, SHEET = ${SHEET}, FRAMES = ${FRAMES}, FPS = ${FPS},`,
    "    sheets = {",
  ];
  for (const cls of CLASS_ORDER) {
    const t = by[cls];
    if (!t) continue;
    lines.push(`        ${cls} = { ${[0, 1, 2].map(i => t[i] ? `"${sheetName(t[i])}"` : 'false').join(', ')} },`);
  }
  lines.push("    },", "}", "");
  return lines.join('\n');
}

// ---- PNG (preview only) ----
function crc32(buf) { let c, crc = 0xffffffff; for (let n = 0; n < buf.length; n++) { c = (crc ^ buf[n]) & 0xff; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crc = (crc >>> 8) ^ c; } return (crc ^ 0xffffffff) >>> 0; }
function chunk(type, data) { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td)); return Buffer.concat([len, td, crc]); }
function png(w, h, rgb) {
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) { raw[y * (w * 3 + 1)] = 0; rgb.copy(raw, y * (w * 3 + 1) + 1, y * w * 3, (y + 1) * w * 3); }
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

function seam(fr) {
  const diff = (a, b) => { let c = 0; for (let i = 0; i < a.length; i += 4) if (a[i] !== b[i] || a[i + 1] !== b[i + 1] || a[i + 2] !== b[i + 2]) c++; return c; };
  const steps = fr.map((d, f) => diff(d, fr[(f + 1) % fr.length]));
  const inner = steps.slice(0, -1).sort((a, b) => a - b);
  return { wrap: steps[steps.length - 1], med: inner[inner.length >> 1], max: inner[inner.length - 1] };
}

function main() {
  const [cmd, a, b, c, d] = process.argv.slice(2);
  // preview and stats of one class load only that class's file, so a half written file elsewhere cannot break them
  const one = (cmd === 'preview' || cmd === 'stats') && a && a !== 'all' ? a.toLowerCase().split('_')[0] : null;
  const { TBG, W, H } = loadScenes(one);
  if (cmd === 'sheets' || cmd === 'check') {
    const media = a || DEFAULT_MEDIA, man = b || DEFAULT_MANIFEST;
    let bad = 0;
    for (const s of TBG.scenes) {
      const buf = sheetTga(frames(TBG, s), W, H), file = path.join(media, sheetName(s) + '.tga');
      if (cmd === 'sheets') fs.writeFileSync(file, buf);
      else if (!fs.existsSync(file) || !fs.readFileSync(file).equals(buf)) { console.log('stale: ' + file); bad++; }
    }
    const text = manifest(TBG.scenes);
    if (cmd === 'sheets') fs.writeFileSync(man, text);
    else if (!fs.existsSync(man) || fs.readFileSync(man, 'utf8') !== text) { console.log('stale: ' + man); bad++; }
    console.log(`${cmd}: ${TBG.scenes.length} scenes` + (cmd === 'check' ? (bad ? `, ${bad} stale` : ', all current') : ''));
    process.exit(bad ? 1 : 0);
  }
  if (cmd === 'stats') {
    for (const s of pick(TBG, a)) { const fr = frames(TBG, s), sm = seam(fr); console.log(`${s.id.padEnd(24)} ${String(s.pal.length).padStart(3)} colours  wrap ${sm.wrap}  median step ${sm.med}  max ${sm.max}`); }
    return;
  }
  if (cmd === 'preview') {
    const sel = pick(TBG, a), out = b, sc = +(c || 2), picks = (d || '0,6,12,18').split(',').map(Number);
    const gap = 6, fw = W * sc, fh = H * sc, ow = picks.length * (fw + gap) - gap, oh = sel.length * (fh + gap) - gap;
    const rgb = Buffer.alloc(ow * oh * 3, 0x14);
    sel.forEach((s, row) => {
      picks.forEach((f, col) => {
        const dd = TBG.render(s, f % FRAMES, FRAMES), ox = col * (fw + gap), oy = row * (fh + gap);
        for (let y = 0; y < fh; y++) for (let x = 0; x < fw; x++) {
          const j = (Math.floor(y / sc) * W + Math.floor(x / sc)) * 4, i = ((oy + y) * ow + ox + x) * 3;
          rgb[i] = dd[j]; rgb[i + 1] = dd[j + 1]; rgb[i + 2] = dd[j + 2];
        }
      });
    });
    fs.writeFileSync(out, png(ow, oh, rgb));
    console.log(`preview: ${sel.map(s => s.id).join(', ')} frames ${picks.join(',')} -> ${out}`);
    return;
  }
  console.error('usage: bake.mjs sheets|check|preview|stats ...');
  process.exit(2);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
