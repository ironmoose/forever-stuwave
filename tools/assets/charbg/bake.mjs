// Bakes the character window backdrop scene (talentbg/lib.js on a 160 x 192 canvas + charbg/scenes/*.js) into the addon's
// flipbook sheet and manifest. candidates/ holds the scenes that were not picked; they are not baked.
//
//   node tools/assets/charbg/bake.mjs sheets [mediaDir] [manifest.lua]   write the sheet and the manifest
//   node tools/assets/charbg/bake.mjs check  [mediaDir] [manifest.lua]   exit 1 unless the committed files equal a fresh bake
//   node tools/assets/charbg/bake.mjs frames <outDir>                    raw RGBA frames per scene (<id>.rgba, 24 frames back to back)
//   node tools/assets/charbg/bake.mjs stats                              colours and loop seam per scene
//
// The sheet is one 1024 x 1024 32-bit TGA: 24 frames of 160 x 192 in 6 columns x 4 rows, each frame with a one texel
// replicated gutter (cell pitch 162 x 194). Alpha is 255 everywhere: the runtime insets the picture inside the well's cut corners.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ADDON = path.resolve(HERE, '../../../forever-stuwave');
const DEFAULT_MEDIA = path.join(ADDON, 'Media/Textures');
const DEFAULT_MANIFEST = path.join(ADDON, 'Modules/Skins/CharBgArt.lua');
export const W = 160, H = 192, FRAMES = 24, FPS = 8, COLS = 6, ROWS = 4, CW = W + 2, CH = H + 2, SHEET = 1024;

export function loadScenes() {
  const ctx = vm.createContext({ SCENE_W: W, SCENE_H: H, Math, Map, Set, Uint8Array, Uint8ClampedArray, Int16Array, Float64Array,
    Float32Array, Uint16Array, Uint32Array, Int32Array, Array, Object, Number, Error, console });
  const files = [path.join(HERE, '../talentbg/lib.js')];
  const dir = path.join(HERE, 'scenes');
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort()) files.push(path.join(dir, f));
  for (const f of files) vm.runInContext(fs.readFileSync(f, 'utf8'), ctx, { filename: f });
  const TBG = vm.runInContext('TBG', ctx);
  if (vm.runInContext('W', ctx) !== W || vm.runInContext('H', ctx) !== H) throw new Error('canvas size not applied');
  TBG.scenes.sort((a, b) => a.tree - b.tree);
  return TBG;
}

function frames(TBG, s) {
  const out = [];
  for (let f = 0; f < FRAMES; f++) out.push(Uint8Array.from(TBG.render(s, f, FRAMES)));
  return out;
}

function sheetTga(fr) {
  const head = Buffer.alloc(18);
  head.writeUInt8(2, 2);
  head.writeUInt16LE(SHEET, 12); head.writeUInt16LE(SHEET, 14); head.writeUInt8(32, 16); head.writeUInt8(0x28, 17);
  const body = Buffer.alloc(SHEET * SHEET * 4);
  for (let i = 3; i < body.length; i += 4) body[i] = 255;
  fr.forEach((d, f) => {
    const ox = (f % COLS) * CW, oy = Math.floor(f / COLS) * CH;
    for (let y = 0; y < CH; y++) {
      const sy = Math.min(H - 1, Math.max(0, y - 1));
      for (let x = 0; x < CW; x++) {
        const sx = Math.min(W - 1, Math.max(0, x - 1)), i = ((oy + y) * SHEET + ox + x) * 4, j = (sy * W + sx) * 4;
        body[i] = d[j + 2]; body[i + 1] = d[j + 1]; body[i + 2] = d[j]; body[i + 3] = 255;
      }
    }
  });
  return Buffer.concat([head, body]);
}

const sheetName = s => 'charbg_' + s.id.replace(/^char_/, '');

function manifest(scenes) {
  return [
    "-- Forever STUwave: the character window backdrop flipbook.",
    "-- GENERATED by tools/assets/charbg/bake.mjs; do not edit (charbg-harness.py checks it).",
    "-- FRAMES cells of W x H texels at pitch CW x CH (one texel gutter round each), COLS across, in a SHEET x SHEET texture.",
    "-- sheet = file name in Media/Textures.",
    "",
    "local _, FS = ...",
    "",
    "FS.CharBgArt = {",
    `    W = ${W}, H = ${H}, CW = ${CW}, CH = ${CH}, COLS = ${COLS}, ROWS = ${ROWS}, SHEET = ${SHEET}, FRAMES = ${FRAMES}, FPS = ${FPS},`,
    `    sheet = "${sheetName(scenes[0])}",`,
    "}",
    "",
  ].join('\n');
}

function seam(fr) {
  const diff = (a, b) => { let c = 0; for (let i = 0; i < a.length; i += 4) if (a[i] !== b[i] || a[i + 1] !== b[i + 1] || a[i + 2] !== b[i + 2]) c++; return c; };
  const steps = fr.map((d, f) => diff(d, fr[(f + 1) % fr.length]));
  const inner = steps.slice(0, -1).sort((a, b) => a - b);
  return { wrap: steps[steps.length - 1], med: inner[inner.length >> 1], max: inner[inner.length - 1] };
}

function main() {
  const [cmd, a] = process.argv.slice(2);
  const TBG = loadScenes();
  if (cmd === 'sheets' || cmd === 'check') {
    if (TBG.scenes.length !== 1) throw new Error(`expected one scene in scenes/, found ${TBG.scenes.length}`);
    const media = a || DEFAULT_MEDIA, man = process.argv[4] || DEFAULT_MANIFEST, s = TBG.scenes[0];
    let bad = 0;
    const buf = sheetTga(frames(TBG, s)), file = path.join(media, sheetName(s) + '.tga'), text = manifest(TBG.scenes);
    if (cmd === 'sheets') { fs.writeFileSync(file, buf); fs.writeFileSync(man, text); }
    else {
      if (!fs.existsSync(file) || !fs.readFileSync(file).equals(buf)) { console.log('stale: ' + file); bad++; }
      if (!fs.existsSync(man) || fs.readFileSync(man, 'utf8') !== text) { console.log('stale: ' + man); bad++; }
    }
    console.log(`${cmd}: ${s.id}` + (cmd === 'check' ? (bad ? `, ${bad} stale` : ', all current') : ''));
    process.exit(bad ? 1 : 0);
  }
  if (cmd === 'frames') {
    fs.mkdirSync(a, { recursive: true });
    for (const s of TBG.scenes) {
      const t0 = Date.now(), fr = frames(TBG, s);
      fs.writeFileSync(path.join(a, s.id + '.rgba'), Buffer.concat(fr.map(d => Buffer.from(d))));
      console.log(`${s.id} ${Date.now() - t0} ms`);
    }
    return;
  }
  if (cmd === 'stats') {
    for (const s of TBG.scenes) { const fr = frames(TBG, s), sm = seam(fr); console.log(`${s.id.padEnd(18)} ${String(s.pal.length).padStart(3)} colours  wrap ${sm.wrap}  median step ${sm.med}  max ${sm.max}`); }
    return;
  }
  console.error('usage: bake.mjs sheets|check [media] [manifest] | frames <dir> | stats');
  process.exit(2);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
