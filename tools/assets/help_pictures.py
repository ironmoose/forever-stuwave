#!/usr/bin/env python3
"""Bakes the Help page pictures, and renders the same annotated pictures for the CurseForge listing.

ONE source: forever-stuwave/Modules/Config/HelpModules.lua (the parts, the pins, the words and the Layout function).
This script runs that Lua file itself, so the listing images are laid out by the very function the Help page calls.

    help_pictures.py                 write Media/Textures/help_pictures.tga and Modules/Config/HelpPicturesArt.lua
    help_pictures.py --check         exit 1 when the committed atlas or manifest differs from a fresh bake
    help_pictures.py --listing DIR   render DIR/help-<class>[-<page>].png and DIR/help-listing.json (the lines)

The pictures are tools/assets/help_frames/<name>.png (cut from the showcase renders by help_frames.py), one texel per
art pixel. The atlas packs them in rows with a clear texel between, uncompressed 32 bit TGA, top left origin.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

try:
    from lupa.luajit21 import LuaRuntime
except ImportError:
    sys.exit("lupa is missing; run under uv (uv run python tools/assets/help_pictures.py)")

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
ADDON = REPO / "forever-stuwave"
DATA = ADDON / "Modules/Config/HelpModules.lua"
MANIFEST = ADDON / "Modules/Config/HelpPicturesArt.lua"
ATLAS = ADDON / "Media/Textures/help_pictures.tga"
FRAMES = HERE / "help_frames"
FONT = ADDON / "Media/Fonts/MononokiNerdFontMono-Bold.ttf"
ATLAS_W, ATLAS_H = 1024, 512
CONTENT_W = 550            # the config window's content width (ConfigWindow.lua CONTENT_W); the listing uses it too

# Theme.lua colours, the same ones ConfigWindow.lua draws the Help page with
PINK = (255, 46, 151)
CYAN = (34, 224, 255)
INK = (10, 4, 22)
MUTED = (157, 147, 196)
WELL = (13, 6, 32)
LINE = (58, 33, 104)
TRACK = (10, 4, 22)


def load_data() -> dict:
    """Run HelpModules.lua and return it as plain Python (lists for Lua arrays)."""
    lua = LuaRuntime(unpack_returned_tuples=True)
    FS = lua.table()
    lua.execute("return function(src, FS) assert(load(src, '@HelpModules.lua'))('forever-stuwave', FS) end")(
        DATA.read_text(encoding="utf-8"), FS)
    return {"lua": lua, "H": FS.HelpModules}


def py(v):
    """A Lua table as list (1..n keys) or dict."""
    if hasattr(v, "keys"):
        keys = list(v.keys())
        if keys and all(isinstance(k, int) for k in keys) and sorted(keys) == list(range(1, len(keys) + 1)):
            return [py(v[k]) for k in range(1, len(keys) + 1)]
        return {k: py(v[k]) for k in keys}
    return v


def pages(H) -> list[tuple[str, int, dict]]:
    out = []
    for token in py(H.ORDER):
        for i, page in enumerate(py(H.CLASSES[token]["pages"]), 1):
            out.append((token, i, page))
    return out


def picture_names(H) -> list[str]:
    names: list[str] = []
    for _, _, page in pages(H):
        for n in [page["picture"]] + [e["picture"] for e in page.get("extras", [])]:
            if n not in names:
                names.append(n)
    return names


def pack(names: list[str]) -> tuple[Image.Image, dict[str, tuple[int, int, int, int]]]:
    """Shelf pack, tallest first, one clear texel between pictures."""
    ims = {n: Image.open(FRAMES / f"{n}.png").convert("RGBA") for n in names}
    order = sorted(names, key=lambda n: (-ims[n].height, -ims[n].width, n))
    atlas = Image.new("RGBA", (ATLAS_W, ATLAS_H), (0, 0, 0, 0))
    rects: dict[str, tuple[int, int, int, int]] = {}
    x = y = shelf = 0
    for n in order:
        im = ims[n]
        if x + im.width > ATLAS_W:
            x, y, shelf = 0, y + shelf + 1, 0
        if y + im.height > ATLAS_H:
            raise SystemExit(f"help atlas full at {n}; grow ATLAS_H")
        atlas.paste(im, (x, y))
        rects[n] = (x, y, im.width, im.height)
        x += im.width + 1
        shelf = max(shelf, im.height)
    return atlas, rects


def tga_bytes(im: Image.Image) -> bytes:
    header = bytes([0, 0, 2]) + bytes(9) + im.width.to_bytes(2, "little") + im.height.to_bytes(2, "little") + bytes([32, 0x28])
    r, g, b, a = im.split()
    return header + Image.merge("RGBA", (b, g, r, a)).tobytes()


def manifest_text(rects: dict[str, tuple[int, int, int, int]]) -> str:
    lines = [
        "local _, FS = ...",
        "",
        "-- GENERATED by tools/assets/help_pictures.py from HelpModules.lua and tools/assets/help_frames/. Do not edit.",
        "-- Where each Help page picture sits in help_pictures.tga, in texels: x, y, width, height.",
        "FS.HelpPicturesArt = {",
        '    file = "help_pictures",',
        f"    width = {ATLAS_W}, height = {ATLAS_H},",
        "    rects = {",
    ]
    for n in sorted(rects):
        x, y, w, h = rects[n]
        lines.append(f"        {n} = {{ {x}, {y}, {w}, {h} }},")
    lines += ["    },", "}", ""]
    return "\n".join(lines)


def bake() -> tuple[bytes, str]:
    H = load_data()["H"]
    atlas, rects = pack(picture_names(H))
    return tga_bytes(atlas), manifest_text(rects)


def size_fn(lua):
    def size(name):
        im = Image.open(FRAMES / f"{name}.png")
        return im.width, im.height
    return size


def render_page(H, lua, page_table, factor: int) -> Image.Image:
    """The Help page's picture block (the box, the picture, the arrows, the pins, the extras) at `factor` x."""
    sizes = {}

    def size(name):
        if name not in sizes:
            im = Image.open(FRAMES / f"{name}.png")
            sizes[name] = (im.width, im.height)
        return sizes[name]

    L = py(H.Layout(page_table, CONTENT_W, size))
    F = factor
    img = Image.new("RGB", (int(L["w"]) * F, int(L["h"]) * F), WELL)
    d = ImageDraw.Draw(img)
    bx, by, bw, bh = (int(v) * F for v in L["box"])
    d.rectangle((bx, by, bx + bw - 1, by + bh - 1), fill=TRACK, outline=LINE, width=F)
    name, px, py_, pw, ph = L["picture"]
    pic = Image.open(FRAMES / f"{name}.png").convert("RGB")
    img.paste(pic.resize((int(pw) * F, int(ph) * F), Image.NEAREST), (int(px) * F, int(py_) * F))
    for x, y, w, h in L["arrows"]:
        d.rectangle((int(x * F), int(y * F), int((x + w) * F) - 1, int((y + h) * F) - 1), fill=CYAN)
    font = ImageFont.truetype(str(FONT), 12 * F)
    pin = int(py(H.PIN))

    def badge(n, x, y):
        d.rectangle((x * F, y * F, (x + pin) * F - 1, (y + pin) * F - 1), fill=PINK)
        d.text(((x + pin / 2) * F, (y + pin / 2) * F), str(n), fill=INK, font=font, anchor="mm")

    for n, x, y in L["pins"]:
        badge(int(n), int(x), int(y))
    if L.get("caption") is not None:
        cap = ImageFont.truetype(str(FONT), 11 * F)
        d.text((0, int(L["caption"]) * F + 2 * F), "OTHER STATES", fill=MUTED, font=cap)
    for n, ename, x, y, w, h in L.get("extras", []):
        x, y, w, h = int(x), int(y), int(w), int(h)
        im = Image.open(FRAMES / f"{ename}.png").convert("RGB")
        img.paste(im.resize((w * F, h * F), Image.NEAREST), (x * F, y * F))
        d.rectangle((x * F, y * F, (x + w) * F - 1, (y + h) * F - 1), outline=LINE, width=F)
        badge(int(n), x, y)
    return img


def listing(out_dir: Path, factor: int) -> None:
    data = load_data()
    H, lua = data["H"], data["lua"]
    out_dir.mkdir(parents=True, exist_ok=True)
    result = {}
    for token in py(H.ORDER):
        class_pages = H.CLASSES[token]["pages"]
        entries = []
        n_pages = len(py(class_pages))
        for i in range(1, n_pages + 1):
            page = class_pages[i]
            p = py(page)
            stem = f"help-{token.lower()}" + (f"-{p['label'].split()[0].lower()}" if n_pages > 1 else "")
            render_page(H, lua, page, factor).save(out_dir / f"{stem}.png")
            pinned = {pin[0] for pin in p.get("pins", [])} | {e["n"] for e in p.get("extras", [])}
            entries.append({"label": p.get("label"), "image": f"{stem}.png",
                            "lines": [{"n": k, "name": nm, "text": tx, "shown": k in pinned}
                                      for k, (nm, tx) in enumerate(p["lines"], 1)],
                            "note": p.get("note")})
        result[token] = entries
    (out_dir / "help-listing.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--listing", type=Path)
    ap.add_argument("--factor", type=int, default=2)
    a = ap.parse_args()
    if a.listing:
        listing(a.listing, a.factor)
        return 0
    tga, manifest = bake()
    if a.check:
        stale = [p.name for p, want in ((ATLAS, tga), (MANIFEST, manifest.encode()))
                 if not p.exists() or p.read_bytes() != want]
        if stale:
            print(f"stale, rerun tools/assets/help_pictures.py: {stale}")
            return 1
        print("help pictures up to date")
        return 0
    ATLAS.write_bytes(tga)
    MANIFEST.write_text(manifest, encoding="utf-8")
    print(f"wrote {ATLAS.relative_to(REPO)} and {MANIFEST.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
