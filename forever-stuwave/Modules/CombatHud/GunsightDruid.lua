    PaintCommon(now)
    if kind == "moon" then PaintMoon(now)
    elseif kind == "cat" then PaintCat(now)
    elseif kind == "bear" then PaintBear(now)
    elseif kind == "tree" then PaintTree(now)
    else
        ShowDot(P.travelLine, G.MOON_X, G.DRAIN_Y + 3, 92, 1, K.line, 0.6)
    end
end
