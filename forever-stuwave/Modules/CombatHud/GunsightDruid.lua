function Druid.Origin() return OX, OY end

local function SeatModule(rect)
    if type(rect) ~= "table" then return end
    local x, y, w = rect.x, rect.y, rect.w
    if type(x) ~= "number" or type(y) ~= "number" or type(w) ~= "number" then return end
    OX, OY = x + (w - C.SW * C.SPX) / 2, y + C.DROP
    if mod then
        SeatAll()
        if subscribed then SafePaint(GetTime()) end
    end
end

local function BuildModule(host)
    if mod then return mod end
    mod = CreateFrame("Frame", "ForeverSTUwaveGunsightDruid", host)
    art = CreateFrame("Frame", nil, mod)
    bars = CreateFrame("Frame", nil, mod)
    top = CreateFrame("Frame", nil, mod)
    Seat(function()
        Gunsight.Point(mod, "TOPLEFT", OX, OY)
        mod:SetSize(ui(C.SW * C.SPX), ui(C.SH * C.SPX))
        art:SetAllPoints(mod)
        bars:SetAllPoints(mod)
        top:SetAllPoints(mod)
    end)
    pcall(function()
        bars:SetFrameLevel(mod:GetFrameLevel() + 1)
        top:SetFrameLevel(mod:GetFrameLevel() + 2)
    end)
    local ok, err = pcall(Build)
    if not ok then
        LogOnce("build", err)
        mod:Hide()
        mod, art, bars, top = nil, nil, nil, nil
        seats, P = {}, {}
        return nil
    end
    SeatAll()
    Druid.frame, Druid.parts = mod, P
    if State.Start then State.Start() end            -- the ledger listens from here on and never stops
    pcall(ReadAll)
    SafePaint(GetTime())
    return mod
end

local function OnAreaShown()
    if not mod then return end
    if not subscribed then
        subscribed = true
        State.Subscribe(OnState)
        SetEvents(true)
    end
    OnState()
    SafePaint(GetTime())
    Sync()
end

local function OnAreaHidden()
    if not mod then return end
    if subscribed then
        subscribed = false
        State.Unsubscribe(OnState)
        SetEvents(false)
    end
    Sync()
end

local okReg, result = pcall(Areas.RegisterModule, "class", {
    classes = { "DRUID" },
    build = BuildModule, seat = SeatModule, onShow = OnAreaShown, onHide = OnAreaHidden,
})
if not okReg or not result then
    LogOnce("register", "FS.GunsightAreas.RegisterModule refused the class module (" .. tostring(result) .. ")")
end
