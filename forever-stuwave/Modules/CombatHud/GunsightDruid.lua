-- a whole count of at least 0, or nil (a secret, a string, a NaN)
local function PlainCount(v)
    if IsSecret(v) or type(v) ~= "number" or v ~= v or v < 0 then return nil end
    return floor(v)
end

local function PowerType(name, fallback)
    local E = _G.Enum
    local pt = E and E.PowerType
    return (pt and pt[name]) or fallback
end
local POW_RAGE, POW_ENERGY, POW_COMBO = PowerType("Rage", 1), PowerType("Energy", 3), PowerType("ComboPoints", 4)

local function Power(kind)
    if type(UnitPower) ~= "function" then return nil end
    local ok, v = pcall(UnitPower, "player", kind)
    if not ok then return nil end
    return v
end

local function PowerMax(kind)
    if type(UnitPowerMax) ~= "function" then return 100 end
    local ok, v = pcall(UnitPowerMax, "player", kind)
    local n = ok and PlainCount(v) or nil
    return (n and n > 0) and n or 100
end

-- the maximum a baked fill's bar is given: the art is FILL_W of the file's FILL_BOX_W, so the bar scales it
local function FillMax(maxPower) return maxPower * G.FILL_BOX_W / G.FILL_W end

local function SetMaxes()
    SetBar(P.energyBar, 0, FillMax(PowerMax(POW_ENERGY)))
    SetBar(P.rageBar, 0, FillMax(PowerMax(POW_RAGE)))
    for i = 1, G.SLASH_N do
        SetBar(P.slashBar[i], i - 1, i)
        SetBar(P.flareBar[i], G.SLASH_N - 1, G.SLASH_N)
    end
end

local function FeedPower()
    local kind = D.kind
    if kind == "cat" then
        local e = Power(POW_ENERGY)
        -- a secret is tested first: an equality test on a secret is refused by the client
        local hasE = IsSecret(e) or e ~= nil
        D.energyNum = (hasE and not IsSecret(e)) and PlainCount(e) or nil
        if hasE then P.energyBar:SetValue(e); TextCount(P.energyNum, e) else P.energyBar:SetValue(0); TextWord(P.energyNum, "") end
        local c = Power(POW_COMBO)
        local feed = 0
        if IsSecret(c) then D.combo, feed = nil, c
        elseif c == nil then D.combo = nil
        else
            local n = PlainCount(c)
            D.combo = n and min(n, G.SLASH_N) or nil
            feed = D.combo or 0
        end
        for i = 1, G.SLASH_N do
            P.slashBar[i]:SetValue(feed)
            P.flareBar[i]:SetValue(feed)
        end
    elseif kind == "bear" then
        local r = Power(POW_RAGE)
        local hasR = IsSecret(r) or r ~= nil
        D.rageNum = (hasR and not IsSecret(r)) and PlainCount(r) or nil
        if hasR then P.rageBar:SetValue(r); TextCount(P.rageNum, r) else P.rageBar:SetValue(0); TextWord(P.rageNum, "") end
    end
end

local function ChipStatus(ch, status, key)
    if ch.status == status then return end
    ch.status = status
    ch.timer = false
    if status ~= "cool" then
        ch.bar:SetValue(status == "ready" and 1 or 0)
    elseif status == "cool" then
        local obj = State.Duration(key)
        local E = _G.Enum
        local dir = E and E.StatusBarTimerDirection and E.StatusBarTimerDirection.ElapsedTime
        local interp = E and E.StatusBarInterpolation and E.StatusBarInterpolation.Immediate
        ch.timer = obj ~= nil and dir ~= nil and ch.bar.SetTimerDuration ~= nil
            and pcall(ch.bar.SetTimerDuration, ch.bar, obj, interp, dir) or false
        if not ch.timer then ch.bar:SetValue(0) end
    end
end

-- everything that is read once per event: the kind, the cooldown flags, the plain power reads
local function ReadAll()
    D.reduced = ReducedMotion()
    local kind = State.Kind()
    if kind ~= D.kind then
        D.kind = kind
        D.combo, D.energyNum, D.rageNum = nil, nil, nil
        if P.energyBar then SetMaxes() end
    end
    D.shiftAt = State.Stamp("shiftAt")
    if P.chipSp then
        if kind == "cat" then D.spStatus = State.Cooldown("shift"); ChipStatus(P.chipSp, D.spStatus, "shift")
        elseif kind == "bear" then D.pbStatus = State.Cooldown("bite"); ChipStatus(P.chipPb, D.pbStatus, "bite")
        elseif kind == "tree" then
            local st = State.Cooldown("swift")
            local now = GetTime()
            if st == "ready" and not (State.Hot("rejuv", now) or State.Hot("regrow", now)) then st = "idle" end
            D.smStatus = st
            ChipStatus(P.chipSm, st, "swift")
        end
        FeedPower()
    end
end

