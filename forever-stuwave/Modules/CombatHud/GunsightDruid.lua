local function Place(t, x, y)
    if t.fsX == x and t.fsY == y then return end
    t.fsX, t.fsY = x, y
    t:ClearAllPoints()
    t:SetPoint("TOPLEFT", t.fsHost, "TOPLEFT", S(x), -S(y))
end

local function On(t)
    if t.fsOn ~= true then t.fsOn = true; t:Show() end
end

local function Off(t)
    if t.fsOn ~= false then t.fsOn = false; t:Hide() end
end

local function Tint(t, c, a)
    local r, g, b = c[1], c[2], c[3]
    if t.fsR == r and t.fsG == g and t.fsB == b and t.fsA == a then return end
    t.fsR, t.fsG, t.fsB, t.fsA = r, g, b, a
    t:SetVertexColor(r, g, b, a)
end

local function Stepped(v) return floor(v * 20 + 0.5) / 20 end

local function SetTex(t, path)
    local ok = pcall(t.SetTexture, t, path, "CLAMP", "CLAMP", "NEAREST")
    if not ok then t:SetTexture(path) end
end

local function Reg(group, t)
    local g = groups[group]
    g[#g + 1] = t
    return t
end

-- A sprite region: an atlas texture on `host`.
local function Spr(group, layer, sub, host)
    host = host or art
    local t = host:CreateTexture(nil, layer, nil, sub or 0)
    t.fsHost = host
    t:Hide()
    t.fsOn = false
    SetTex(t, MEDIA .. ATL.file .. ".tga")
    t.fsAtlasSet = true
    Seat(function() t.fsX, t.fsY, t.fsName = nil, nil, nil end)
    return Reg(group, t)
end

-- A sprite region on the Thorns atlas.
local function SprT(layer, sub, host)
    local t = Spr("thorns", layer, sub, host)
    SetTex(t, MEDIA .. TATL.file .. ".tga")
    t.fsSpr, t.fsAtl = TSPR, TATL
    return t
end

-- A flat region (one sprite px unless sized).
local function Dot(group, layer, sub, host)
    host = host or art
    local t = host:CreateTexture(nil, layer, nil, sub or 0)
    t.fsHost = host
    t:SetTexture(FLAT)
    t:Hide()
    t.fsOn = false
    t.fsW, t.fsH = 1, 1
    Seat(function() t:SetSize(S(t.fsW), S(t.fsH)); t.fsX, t.fsY = nil, nil end)
    return Reg(group, t)
end

local function DotSize(t, w, h)
    if t.fsW == w and t.fsH == h then return end
    t.fsW, t.fsH = w, h
    t:SetSize(S(w), S(h))
end

local function ShowDot(t, x, y, w, h, c, a)
    if a <= 0 or w <= 0 or h <= 0 then Off(t); return end
    On(t)
    DotSize(t, w, h)
    Place(t, x, y)
    Tint(t, c, a)
end

-- Show sprite `name` with its origin at sprite (x, y); `flip` mirrors it (and its origin).
local function Sprite(t, name, x, y, c, a, flip)
    local s = name and (t.fsSpr or SPR)[name]
    if not s or a <= 0 then Off(t); return end
    local w, h = s[3], s[4]
    if t.fsName ~= name or t.fsFlip ~= flip then
        t.fsName, t.fsFlip = name, flip
        local atl = t.fsAtl or ATL
        local aw, ah = atl.w, atl.h
        local l, r = s[1] / aw, (s[1] + w * SCALE) / aw
        if flip then l, r = r, l end
        t:SetTexCoord(l, r, s[2] / ah, (s[2] + h * SCALE) / ah)
        t:SetSize(S(w), S(h))
        t.fsX = nil
    end
    On(t)
    Place(t, x - (flip and (w - 1 - s[5]) or s[5]), y - s[6])
    Tint(t, c, a)
end

local function Text(group, align, size)
    local fs = top:CreateFontString(nil, "OVERLAY")
    fs.fsAlign, fs.fsPx = align or "LEFT", size or 8
    fs.fsCol, fs.fsA = K.muted, 1
    fs.fsHost = art
    fs:Hide()
    fs.fsOn = false
    Seat(function()
        local T = FS.Theme
        if T and T.ApplyMono then T.ApplyMono(fs, S(fs.fsPx), { fs.fsCol[1], fs.fsCol[2], fs.fsCol[3], fs.fsA }) end
        fs.fsX = nil
    end)
    return Reg(group, fs)
end

local function TextAt(fs, x, y)
    if fs.fsX == x and fs.fsY == y then return end
    fs.fsX, fs.fsY = x, y
    fs:ClearAllPoints()
    fs:SetPoint(fs.fsAlign, art, "TOPLEFT", S(x), -S(y))
end

local function TextColor(fs, c, a)
    if fs.fsCol == c and fs.fsA == a then return end
    fs.fsCol, fs.fsA = c, a
    fs:SetTextColor(c[1], c[2], c[3], a)
end

local function TextWord(fs, word)
    if fs.fsWord == word then return end
    fs.fsWord = word
    fs.fsNum = nil
    fs:SetText(word)
end

-- "~%ds" with the engine doing the formatting; only when the whole second changed
local function TextSecs(fs, secs)
    local n = math.ceil(secs)
    if fs.fsNum == n and fs.fsWord == nil then return end
    fs.fsNum, fs.fsWord = n, nil
    fs:SetFormattedText("~%ds", n)
end

local function TextCount(fs, value)
    fs.fsWord, fs.fsNum = nil, nil
    local ok = pcall(fs.SetFormattedText, fs, "%d", value)
    if not ok then fs:SetText("") end
end

-- A StatusBar whose texture is a baked file; its box is `wpx` x `hpx` sprite px with its top left at (x, y).
local function MakeBar(group, parent, file, wpx, hpx, vertical)
    local bar = CreateFrame("StatusBar", nil, parent)
    bar:EnableMouse(false)
    bar:SetStatusBarTexture(MEDIA .. file .. ".tga")
    if bar.SetOrientation then pcall(bar.SetOrientation, bar, vertical and "VERTICAL" or "HORIZONTAL") end
    bar:SetMinMaxValues(0, 1)
    bar:SetValue(0)
    bar:Hide()
    bar.fsOn, bar.fsHost = false, art
    Seat(function() bar:SetSize(S(wpx), S(hpx)); bar.fsX, bar.fsY = nil, nil end)
    return Reg(group, bar)
end

local function SetBar(bar, lo, hi)
    if bar.fsLo ~= lo or bar.fsHi ~= hi then
        bar.fsLo, bar.fsHi = lo, hi
        bar:SetMinMaxValues(lo, hi)
    end
end

