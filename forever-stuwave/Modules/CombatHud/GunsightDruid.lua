-- the word under the eyes (the mockup's cue(S))
local function ComputeCue(now)
    local kind = D.kind
    local word, color, hot, blink = "", K.muted, false, false
    if kind == "travel" then
        word = "TRAVEL"
    elseif kind == "moon" then
        local mode, charges = State.Eclipse(now)
        if mode == "locked" then word = "ECLIPSE L30"
        elseif mode == "unknown" then word = "?"
        elseif charges > 0 then word, color, hot = "STARFIRE", K.gold, true
        else word, color = "WRATH", K.cyan end
    elseif kind == "cat" then
        word = "CAT"
        local combo = D.combo
        if combo and combo >= G.SLASH_N then word, color, hot = "FINISH", K.amber, true
        elseif combo and D.spStatus == "ready" and D.energyNum and D.energyNum < State.TUNING.ENERGY_NOTCH then word, color, hot = "SHIFT", K.cyan, true end
    elseif kind == "bear" then
        local stacks, left = State.Lacerate(now)
        if stacks >= 5 and left <= C.WARN_S and left > 0 then word, color, hot, blink = "LACERATE", K.amber, true, true
        elseif D.pbStatus == "ready" then word, color, hot = "BITE", K.warm, true
        elseif stacks < 5 then word, color = "LACERATE", K.leaf
        else word = "BEAR" end
    else
        local rj, rg = State.Hot("rejuv", now), State.Hot("regrow", now)
        if not rj then word, color, hot = "REJUV", K.green, true
        elseif not rg then word, color = "REGROWTH", K.pink
        elseif D.smStatus == "ready" then word, color, hot = "SWIFTMEND", K.pink, true
        else word = "HOTS UP" end
    end
    CUE.word, CUE.color, CUE.hot, CUE.blink = word, color, hot, blink
end

local function PaintCommon(now)
    local kind, red = D.kind, D.reduced
    local col = K.form[kind]
    local eyeForm = kind == "travel" and "moon" or kind
    local since = D.shiftAt and (now - D.shiftAt) or 9
    local shifting = not red and since >= 0 and since < 0.3
    local breath = red and 0.5 or (0.5 + 0.5 * sin(now * 2 * pi / 3.2))
    local budA = Stepped(0.35 + 0.35 * breath)
    Sprite(P.ivy[1], "ivy", 1, 1, K.pure, 0.9, false)
    Sprite(P.ivy[2], "ivy", G.W - 2, 1, K.pure, 0.9, true)
    Sprite(P.buds[1], "ivy_buds", 1, 1, col, budA, false)
    Sprite(P.buds[2], "ivy_buds", G.W - 2, 1, col, budA, true)
    local n = NAME.eye[eyeForm]
    local state = CUE.hot and n.hot or n.open
    if kind == "travel" then state = n.half end
    if not red and kind ~= "travel" then
        local bp = (now + 1.3) % 4.6
        if bp > 4.3 and bp < 4.4 then state = n.half
        elseif bp >= 4.4 and bp < 4.5 then state = n.shut
        elseif bp >= 4.5 then state = n.half end
    end
    if shifting then state = since < 0.12 and n.shut or n.half end
    local glowA = CUE.hot and (0.28 + 0.3 * breath) or (kind == "travel" and 0 or (0.1 + 0.08 * breath))
    glowA = Stepped(glowA)
    for side = 1, 2 do
        local ex = side == 2 and G.EYE_R or G.EYE_L
        local flip = side == 2
        if state ~= n.shut and glowA > 0 then Sprite(P.glow[side], n.glow, ex, G.EYE_Y, col, glowA, flip) else Off(P.glow[side]) end
        Sprite(P.eye[side], state, ex, G.EYE_Y, kind == "travel" and K.travelEye or K.pure, 1, flip)
        if shifting then Sprite(P.flash[side], n.glow, ex, G.EYE_Y, K.pure, Stepped(1 - since / 0.3), flip) else Off(P.flash[side]) end
    end
    for i = 1, C.SPARKS do
        if shifting then
            local a, r = (i - 1) * pi / 4 + 0.3, 4 + since * 70
            ShowDot(P.sparks[i], Round(G.GLYPH_X + math.cos(a) * r), Round(G.GLYPH_Y + sin(a) * r * 0.7), 1, 1,
                i % 2 == 0 and col or K.pure, Stepped(1 - since / 0.3))
        else Off(P.sparks[i]) end
    end
    Sprite(P.glyph, NAME.glyph[eyeForm], G.GLYPH_X, G.GLYPH_Y, col, kind == "travel" and 0.4 or (CUE.hot and 1 or 0.8), false)
    local blinkOff = CUE.blink and not red and (floor(now * 4) % 2 == 1)
    if CUE.word ~= "" and not blinkOff then
        On(P.cue)
        TextWord(P.cue, CUE.word)
        TextColor(P.cue, CUE.color, kind == "travel" and 0.7 or 1)
        TextAt(P.cue, G.GLYPH_X, G.CUE_Y)
    else Off(P.cue) end
end

local function PaintMoon(now)
    local red = D.reduced
    local mode, charges, left = State.Eclipse(now)
    local locked, unknown = mode == "locked", mode == "unknown"
    local spendAt, grantAt = State.Stamp("spendAt"), State.Stamp("grantAt")
    local since = spendAt and (now - spendAt) or 9
    local grant = grantAt and (now - grantAt) or 9
    for i = 1, G.MOON_N do
        local m = P.moon[i]
        local x, y = G.MOON_X + G.MOON_STEP * (i - 1), G.MOON_Y
        if locked then
            Sprite(m.dotted, "moon_dotted", x, y, K.pure, 1, false)
            Off(m.dark); Off(m.glow); Off(m.lit)
        else
            Off(m.dotted)
            Sprite(m.dark, "moon_dark", x, y, K.pure, unknown and 0.5 or 1, false)
            if not unknown and i <= charges then
                local pop = (not red and grant >= 0 and grant < 0.3 and i > charges - 2) and (1 - grant / 0.3) or 0
                local hold = 0.35 + 0.2 * (red and 0.5 or (0.5 + 0.5 * sin(now * 2 * pi / 2.4)))
                Sprite(m.glow, "moon_glow", x, y, K.gold, Stepped(hold + pop * 0.5), false)
                Sprite(m.lit, "moon_lit", x, y, pop > 0 and K.pop[floor(pop * 3 - 0.001) + 1] or K.moonLit, 1, false)
            elseif not red and not unknown and since >= 0 and since < 0.5 and i == charges + 1 then
                local k = Stepped(1 - since / 0.5)
                Sprite(m.lit, "moon_lit", x, y, K.pure, k, false)
                Sprite(m.glow, "moon_glow", x, y, K.gold, k, false)
            else
                Off(m.lit); Off(m.glow)
            end
        end
    end
    -- the scatter of the spent moon
    for j = 1, C.MOON_SPARKS do
        if not red and not unknown and not locked and since >= 0 and since < 0.5 then
            local a, r = (j - 1) * 1.05 + (charges + 1), 3 + since * 26
            ShowDot(P.moonSparks[j], Round(G.MOON_X + G.MOON_STEP * charges + 9 + math.cos(a) * r), Round(G.MOON_Y + 9 + sin(a) * r), 1, 1,
                j % 2 == 0 and K.gold or K.pure, Stepped(1 - since / 0.5))
        else Off(P.moonSparks[j]) end
    end
    Sprite(P.drainTrack, "track_drain", G.DRAIN_X, G.DRAIN_Y, K.pure, 1, false)
    if locked then
        Off(P.drainBody); Off(P.drainHi); Off(P.drainSecs)
    elseif not unknown and charges > 0 then
        local w = Round((G.DRAIN_W - 2) * max(0, min(1, left / C.ECLIPSE_LEN)))
        local warn = left <= C.WARN_S
        ShowDot(P.drainBody, G.DRAIN_X + 1, G.DRAIN_Y + 1, w, 5, warn and K.drainBodyW or K.drainBody, 1)
        ShowDot(P.drainHi, G.DRAIN_X + 1, G.DRAIN_Y + 1, w, 1, warn and K.drainHiW or K.drainHi, 1)
        On(P.drainSecs)
        TextSecs(P.drainSecs, left)
        TextColor(P.drainSecs, warn and K.amber or K.muted, 1)
        TextAt(P.drainSecs, G.SECS_X, G.SECS_Y)
    else
        Off(P.drainBody); Off(P.drainHi)
        On(P.drainSecs)
        TextWord(P.drainSecs, unknown and "?" or "0")
        TextColor(P.drainSecs, K.muted, 0.6)
        TextAt(P.drainSecs, G.SECS_X, G.SECS_Y)
    end
end

-- a chip: the ring, the dark glyph, the engine's fill, the glow while ready
local function PaintChip(ch, x, y, glow, now, fallbackAt, fallbackLen)
    local st = ch.status
    Sprite(ch.ring, "chip_ring", x - 2, y - 2, st == "ready" and glow or K.pure, 1, false)
    Sprite(ch.dark, ch.darkName, x, y, K.pure, (st == "none") and 0.35 or 1, false)
    if st == "none" then Off(ch.bar); Off(ch.halo); return end
    local bar = ch.bar
    if bar.fsX ~= x or bar.fsY ~= y then
        bar.fsX, bar.fsY = x, y
        bar:ClearAllPoints()
        bar:SetPoint("TOPLEFT", art, "TOPLEFT", S(x), -S(y))
    end
    On(bar)
    if st == "cool" and not ch.timer then
        local frac = fallbackAt and min(1, max(0, (now - fallbackAt) / fallbackLen)) or 0
        frac = Stepped(frac)
        if ch.fallback ~= frac then ch.fallback = frac; bar:SetValue(frac) end
    end
    if st == "ready" then
        local a = D.reduced and 0.45 or (0.25 + 0.3 * (0.5 + 0.5 * sin(now * 2 * pi / 1.6)))
        Sprite(ch.halo, "halo", x + 8, y + 8, glow, Stepped(a), false)
    else Off(ch.halo) end
end

