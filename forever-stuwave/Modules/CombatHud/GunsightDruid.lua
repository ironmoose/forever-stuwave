local function OnState(reason)
    if not mod then return end
    if reason == "cooldown" then
        -- SPELL_UPDATE_COOLDOWN fires many times a second in a fight and a full read allocates (spell lookups and the
        -- cooldown tables), so a burst only moves the next slow poll up to at most 0.1 s away
        pollAcc = math.max(pollAcc, C.POLL - 0.1)
        return
    end
    local ok, err = pcall(ReadAll)
    if not ok then LogOnce("read", err) end
    if subscribed then SafePaint(GetTime()) end
end

local function OnPower(_, event, unit, token)
    if event == "PLAYER_TARGET_CHANGED" then
        OnState()
        return
    end
    if not IsSecret(unit) and unit ~= nil and unit ~= "player" then return end
    if event == "UNIT_MAXPOWER" then pcall(SetMaxes) end
    local ok, err = pcall(FeedPower)
    if not ok then LogOnce("power", err) end
end

local EVENT_LIST = { "PLAYER_TARGET_CHANGED", "UNIT_POWER_FREQUENT", "UNIT_POWER_UPDATE", "UNIT_MAXPOWER" }

local function SetEvents(on)
    local FH = FS.FrameHelpers
    for _, e in ipairs(EVENT_LIST) do
        if on then
            if e == "PLAYER_TARGET_CHANGED" then
                if FH and FH.RegisterEvent then FH.RegisterEvent(mod, e) else pcall(mod.RegisterEvent, mod, e) end
            else
                if FH and FH.RegisterEvent then FH.RegisterEvent(mod, e, "player") else pcall(mod.RegisterUnitEvent, mod, e, "player") end
            end
        else
            pcall(mod.UnregisterEvent, mod, e)
        end
    end
    mod:SetScript("OnEvent", on and OnPower or nil)
end

local function Tick(_, elapsed)
    acc = acc + elapsed
    pollAcc = pollAcc + elapsed
    slowAcc = slowAcc + elapsed
    if slowAcc >= C.TICK_SLOW then
        slowAcc = 0
        State.Tick(GetTime())
    end
    if pollAcc >= C.POLL then
        pollAcc = 0
        OnState()
    end
    if acc < C.TICK then return end
    acc = 0
    SafePaint(GetTime())
end

local function Sync()
    local want = subscribed and mod ~= nil
    if want == ticking then return end
    ticking = want
    acc, pollAcc, slowAcc = 0, 0, 0
    mod:SetScript("OnUpdate", want and Tick or nil)
end

